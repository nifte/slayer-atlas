def loc(id_, name, region, x, y, travel, plane=0, wild=False, path=None):
    location = {
        "id": id_,
        "name": name,
        "region": region,
        "x": x,
        "y": y,
        "plane": plane,
        "wilderness": wild,
        "travel": travel,
    }
    if path:
        location["pathX"] = path[0]
        location["pathY"] = path[1]
        location["pathPlane"] = path[2] if len(path) > 2 else 0
    return location


