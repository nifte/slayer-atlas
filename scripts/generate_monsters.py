def draw_icon(path: Path, size: int) -> None:
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    margin = max(1, size // 24)
    draw.rounded_rectangle(
        [margin, margin, size - 1 - margin, size - 1 - margin],
        radius=size // 6,
        fill=(32, 32, 32, 255),
        outline=(220, 138, 0, 255),
        width=max(2, size // 16),
    )
    # Horned helm
    cx, cy = size // 2, size // 2 + size // 16
    helm = [
        (cx - size * 0.22, cy - size * 0.02),
        (cx - size * 0.18, cy - size * 0.22),
        (cx - size * 0.04, cy - size * 0.12),
        (cx + size * 0.04, cy - size * 0.12),
        (cx + size * 0.18, cy - size * 0.22),
        (cx + size * 0.22, cy - size * 0.02),
        (cx + size * 0.16, cy + size * 0.18),
        (cx - size * 0.16, cy + size * 0.18),
    ]
    draw.polygon(helm, fill=(198, 163, 84, 255), outline=(220, 138, 0, 255))
    draw.polygon(
        [(cx - size * 0.28, cy - size * 0.08), (cx - size * 0.38, cy - size * 0.28), (cx - size * 0.16, cy - size * 0.16)],
        fill=(180, 140, 50, 255),
    )
    draw.polygon(
        [(cx + size * 0.28, cy - size * 0.08), (cx + size * 0.38, cy - size * 0.28), (cx + size * 0.16, cy - size * 0.16)],
        fill=(180, 140, 50, 255),
    )
    slit_w, slit_h = size * 0.07, size * 0.05
    draw.rectangle([cx - size * 0.12, cy, cx - size * 0.12 + slit_w, cy + slit_h], fill=(30, 30, 30, 255))
    draw.rectangle([cx + size * 0.05, cy, cx + size * 0.05 + slit_w, cy + slit_h], fill=(30, 30, 30, 255))
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, "PNG")


def main() -> None:
    seen_loc = {}
    for location in LOCATIONS:
        if location["id"] in seen_loc:
            raise SystemExit(f"Duplicate location id {location['id']}")
        seen_loc[location["id"]] = location

    cleaned = []
    seen_mon = set()
    for monster in MONSTERS:
        if monster["id"] in seen_mon:
            raise SystemExit(f"Duplicate monster id {monster['id']}")
        seen_mon.add(monster["id"])
        missing = [lid for lid in monster["locationIds"] if lid not in seen_loc]
        if missing:
            raise SystemExit(f"{monster['name']} missing locations: {missing}")
        if monster["recommendedLocationId"] not in seen_loc:
            raise SystemExit(f"{monster['name']} bad recommended location")
        if monster["combatLevelMin"] is None or monster["combatLevelMax"] is None:
            raise SystemExit(f"{monster['name']} missing combat levels")
        cleaned.append(monster)

    JSON_PATH.parent.mkdir(parents=True, exist_ok=True)
    JSON_PATH.write_text(json.dumps({"locations": LOCATIONS, "monsters": cleaned}, indent=2) + "\n")
    if Image is None:
        print("Skipping icons (Pillow not installed)")
    else:
        draw_icon(ICON_RESOURCE, 48)
        draw_icon(ICON_HUB, 48)
    print(f"Wrote {len(cleaned)} monsters and {len(LOCATIONS)} locations to {JSON_PATH}")


if __name__ == "__main__":
    main()
